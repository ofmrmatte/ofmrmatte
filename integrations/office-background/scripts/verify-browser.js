async (page) => {
  const base = 'http://127.0.0.1:4173';
  const errors = [], failedRequests = [], stages = [], memoryCycles = [];
  const onConsole = message => { if (message.type() === 'error') errors.push(message.text()); };
  const onError = error => errors.push(error.message);
  const onResponse = response => { if (response.status() >= 400) failedRequests.push({ url: response.url(), status: response.status() }); };
  page.on('console', onConsole); page.on('pageerror', onError); page.on('response', onResponse);
  const check = (condition, message) => { if (!condition) throw new Error(message); };
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.setViewportSize({ width: 1440, height: 960 });
  await page.goto(base);
  await page.waitForFunction(() => window.__officeDiagnostics?.plantLoaded, { timeout: 30000 });
  for (const [i, progress] of [0, .28, .52, .76, 1].entries()) {
    await page.evaluate(p => window.scrollTo({ top: (document.documentElement.scrollHeight - innerHeight) * p, behavior: 'instant' }), progress);
    await page.waitForTimeout(1700);
    const data = await page.evaluate(() => window.__officeDiagnostics);
    check(Math.abs(data.progress - progress) < .005, `Scroll at stage ${i + 1}`);
    check(data.activeScene === i + 1, `Active stage ${i + 1}`);
    check(data.bounds.overlaps.length === 0, `Furniture bounds at stage ${i + 1}`);
    check(data.plantLoaded, 'Real plant asset is loaded');
    await page.screenshot({ path: `artifacts/final/scene-${i + 1}.png` });
    stages.push(data);
  }
  check(stages[3].screenVersions.every((v, i) => v > stages[0].screenVersions[i]), 'IDE, preview and terminal must update');
  await page.getByRole('button', { name: 'Cena 2: APROXIMAÇÃO', exact: true }).click();
  await page.waitForTimeout(2200);
  check(Math.abs((await page.evaluate(() => window.__officeDiagnostics.progress)) - .28) < .005, 'Keyboard-accessible stage navigation');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(2100);
  await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }));
  await page.waitForTimeout(1700);
  const mobile = await page.evaluate(() => ({ ...window.__officeDiagnostics, overflow: document.documentElement.scrollWidth > innerWidth }));
  check(mobile.profile === 'mobile' && !mobile.overflow, 'Mobile profile and horizontal overflow');
  await page.screenshot({ path: 'artifacts/final/mobile-initial.png' });
  await page.evaluate(() => window.scrollTo({ top: (document.documentElement.scrollHeight - innerHeight) * .76, behavior: 'instant' }));
  await page.waitForTimeout(1700);
  await page.screenshot({ path: 'artifacts/final/mobile-workstation.png' });
  await page.setViewportSize({ width: 1024, height: 768 });
  await page.waitForTimeout(2100);
  await page.evaluate(() => window.scrollTo({ top: (document.documentElement.scrollHeight - innerHeight) * .76, behavior: 'instant' }));
  await page.waitForTimeout(1700);
  const tablet = await page.evaluate(() => window.__officeDiagnostics);
  check(tablet.profile === 'tablet', 'Tablet profile');
  await page.screenshot({ path: 'artifacts/final/tablet-workstation.png' });
  for (const width of [1440, 390, 1440, 390, 1440]) {
    await page.setViewportSize({ width, height: width === 390 ? 844 : 960 });
    await page.waitForTimeout(1700);
    memoryCycles.push(await page.evaluate(() => ({ profile: window.__officeDiagnostics.profile, memory: window.__officeDiagnostics.memory })));
  }
  const desktops = memoryCycles.filter(x => x.profile === 'desktop');
  check(desktops.at(-1).memory.geometries <= desktops[0].memory.geometries + 3, 'Geometry count must plateau across resize cycles');
  check(desktops.at(-1).memory.textures <= desktops[0].memory.textures + 1, 'Texture count must plateau across resize cycles');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.evaluate(() => window.scrollTo({ top: document.documentElement.scrollHeight, behavior: 'instant' }));
  await page.waitForTimeout(1700);
  const reduced = await page.evaluate(() => window.__officeDiagnostics);
  check(reduced.reducedMotion, 'Reduced motion media query');
  check(Math.abs(reduced.camera[0] - 2.6) < .01 && Math.abs(reduced.camera[2] - 3.7) < .01, 'Reduced motion keeps an establishing camera');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.goto(`${base}/?progress=0.76&debug`);
  await page.waitForFunction(() => window.__officeDiagnostics?.plantLoaded && window.__officeDiagnostics.progress > .75);
  const external = await page.evaluate(() => ({ ...window.__officeDiagnostics, height: document.documentElement.scrollHeight, viewport: innerHeight }));
  check(external.activeScene === 4 && external.height <= external.viewport + 2, 'External progress prop without a scroll spacer');
  await page.goto(`${base}/?progress=1.5`);
  await page.waitForFunction(() => window.__officeDiagnostics?.progress === 1);
  check((await page.evaluate(() => window.__officeDiagnostics.activeScene)) === 5, 'External progress clamping');
  const attributionStatus = await page.evaluate(async () => (await fetch('/ASSET_CREDITS.md')).status);
  check(attributionStatus === 200, 'Public asset-specific attribution');
  check(errors.length === 0, `Console errors: ${errors.join('; ')}`);
  check(failedRequests.length === 0, `Failed requests: ${JSON.stringify(failedRequests)}`);
  page.off('console', onConsole); page.off('pageerror', onError); page.off('response', onResponse);
  await page.goto(base);
  return { passed: true, errors, failedRequests, stages, mobile, tablet, memoryCycles, reducedMotion: reduced.reducedMotion, externalProgress: external.progress, attributionStatus };
}
